    private void dowfileActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_dowfileActionPerformed
       // TODO add your handling code here:
       try {
            // 1. Chạy ngầm 1 kết nối để xin Server danh sách tên file trước
            java.net.Socket socketList = new java.net.Socket(client.LoginForm.SERVER_IP, 8888);
            java.io.DataOutputStream dosList = new java.io.DataOutputStream(socketList.getOutputStream());
            java.io.DataInputStream disList = new java.io.DataInputStream(socketList.getInputStream());

            dosList.writeUTF("GET_FILE_NAMES");
            dosList.writeUTF("Máy Sinh Viên");
            String fileNamesStr = disList.readUTF();
            socketList.close();

            // Nếu Server trống không có file nào
            if (fileNamesStr.trim().isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Kho lưu trữ trên Server hiện đang trống!", "Thông báo", javax.swing.JOptionPane.WARNING_MESSAGE);
                return; // Ngưng luôn, không hiện bảng tải
            }

            // Cắt chuỗi thành mảng để đưa vào Dropdown menu
           String[] fileList = fileNamesStr.split("\\|");

            // 2. Hiển thị hộp thoại dạng menu xổ xuống cho sinh viên chọn
            String selectedFileName = (String) javax.swing.JOptionPane.showInputDialog(
                    this,
                    "Chọn tài liệu bạn muốn tải về:",
                    "Tải xuống tài liệu",
                    javax.swing.JOptionPane.QUESTION_MESSAGE,
                    null,
                    fileList,
                    fileList[0]);

            // 3. Nếu người dùng đã chọn 1 file và bấm OK
            if (selectedFileName != null) {
                // Hiện tiếp hộp thoại hỏi lưu ở đâu trên máy
                javax.swing.JFileChooser fileChooser = new javax.swing.JFileChooser();
                fileChooser.setSelectedFile(new java.io.File(selectedFileName)); 
                int result = fileChooser.showSaveDialog(this);

                if (result == javax.swing.JFileChooser.APPROVE_OPTION) {
                    java.io.File saveFile = fileChooser.getSelectedFile();
                    textAreaFile.append("Đang yêu cầu tải file: " + selectedFileName + "...\n");

                    // 4. Kết nối mạng lần 2 để chính thức tải file
                    java.net.Socket socket = new java.net.Socket(client.LoginForm.SERVER_IP, 8888);
                    java.io.DataOutputStream dos = new java.io.DataOutputStream(socket.getOutputStream());
                    java.io.DataInputStream dis = new java.io.DataInputStream(socket.getInputStream());

                    dos.writeUTF("DOWNLOAD");
                    dos.writeUTF(client.LoginForm.currentUserInfo);
                    dos.writeUTF(selectedFileName);

                    String status = dis.readUTF();

                    if (status.equals("OK")) {
                        long fileSize = dis.readLong();
                        java.io.FileOutputStream fos = new java.io.FileOutputStream(saveFile);
                        byte[] buffer = new byte[4096];
                        int bytesRead;
                        long totalRead = 0;

                        while (totalRead < fileSize && (bytesRead = dis.read(buffer, 0, (int)Math.min(buffer.length, fileSize - totalRead))) != -1) {
                            fos.write(buffer, 0, bytesRead);
                            totalRead += bytesRead;
                        }
                        fos.close();
                        textAreaFile.append("<<< Đã tải thành công và lưu tại: " + saveFile.getAbsolutePath() + "\n\n");
                    } else {
                        textAreaFile.append("<<< Lỗi: Server báo không tìm thấy file!\n\n");
                    }
                    socket.close();
                }
            }
        } catch (Exception ex) {
            textAreaFile.append("Lỗi tải file: " + ex.getMessage() + "\n\n");
        }
    }//GEN-LAST:event_dowfileActionPerformed

