    private void btnlichsuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnlichsuActionPerformed
try {
    java.net.Socket socket = new java.net.Socket(client.LoginForm.SERVER_IP, 8888);
    java.io.DataOutputStream dos = new java.io.DataOutputStream(socket.getOutputStream());
    java.io.DataInputStream dis = new java.io.DataInputStream(socket.getInputStream());

    dos.writeUTF("VIEW_HISTORY");
    dos.writeUTF(client.LoginForm.currentUserInfo);
    
    String rawData = dis.readUTF();
    socket.close();

    if (rawData.isEmpty() || rawData.equals("Loi DB")) {
        javax.swing.JOptionPane.showMessageDialog(this, "Chưa có dữ liệu lịch sử nào được ghi nhận hoặc lỗi CSDL!");
        return;
    }

    // ĐÃ SỬA: Cắt chuỗi theo <row> và <col>
    String[] rows = rawData.split("<row>");
    String[] columnNames = {"Thời Gian", "Người Thao Tác (Danh Tính - IP)", "Chi Tiết Hành Động"};
    Object[][] dataValues = new Object[rows.length][3];

    for (int i = 0; i < rows.length; i++) {
        if (!rows[i].trim().isEmpty()) {
            String[] cols = rows[i].split("<col>");
            if(cols.length == 3) {
                dataValues[i][0] = cols[0]; 
                dataValues[i][1] = cols[1]; 
                dataValues[i][2] = cols[2]; 
            }
        }
    }

    javax.swing.JFrame historyFrame = new javax.swing.JFrame("Nhật Ký Hệ Thống (Lưu trữ 30 ngày)");
    historyFrame.setSize(1000, 500);
    historyFrame.setLocationRelativeTo(null);

    javax.swing.JTable table = new javax.swing.JTable(dataValues, columnNames);
    table.setRowHeight(30); 
    table.setFont(new java.awt.Font("Arial", java.awt.Font.PLAIN, 14));
    
    table.getColumnModel().getColumn(0).setPreferredWidth(150);
    table.getColumnModel().getColumn(1).setPreferredWidth(350);
    table.getColumnModel().getColumn(2).setPreferredWidth(500);
    
    table.setAutoCreateRowSorter(true);

    javax.swing.JScrollPane scrollPane = new javax.swing.JScrollPane(table);
    historyFrame.add(scrollPane);
    historyFrame.setVisible(true);

} catch (Exception ex) {
    javax.swing.JOptionPane.showMessageDialog(this, "Lỗi kết nối tới Server: " + ex.getMessage());
}
    }//GEN-LAST:event_btnlichsuActionPerformed

    private void btndoiten1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndoiten1ActionPerformed
  try {
    // 1. Chạy ngầm xin danh sách file hiện có
    java.net.Socket socketList = new java.net.Socket(client.LoginForm.SERVER_IP, 8888);
    java.io.DataOutputStream dosList = new java.io.DataOutputStream(socketList.getOutputStream());
    java.io.DataInputStream disList = new java.io.DataInputStream(socketList.getInputStream());

    dosList.writeUTF("GET_FILE_NAMES");
    dosList.writeUTF(client.LoginForm.currentUserInfo);
    String fileNamesStr = disList.readUTF();
    socketList.close();

    if (fileNamesStr == null || fileNamesStr.trim().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Kho lưu trữ trống, không có file để đổi tên!", "Thông báo", javax.swing.JOptionPane.WARNING_MESSAGE);
        return; 
    }

    String[] fileList = fileNamesStr.split("\\|");
    
    // Loại bỏ phần tử rỗng
    java.util.List<String> validFiles = new java.util.ArrayList<>();
    for (String f : fileList) {
        if (!f.trim().isEmpty()) {
            validFiles.add(f);
        }
    }
    if (validFiles.isEmpty()) return;

    // 2. Hiển thị Dropdown menu
    String oldFileName = (String) javax.swing.JOptionPane.showInputDialog(
            this,
            "Chọn tài liệu bạn muốn đổi tên:",
            "Đổi Tên File",
            javax.swing.JOptionPane.QUESTION_MESSAGE,
            null,
            validFiles.toArray(new String[0]),
            validFiles.get(0));

    if (oldFileName != null) {
        // --- BẮT ĐẦU ĐOẠN CẮT ĐUÔI FILE CŨ ---
        String extension = "";
        String baseName = oldFileName;
        int dotIndex = oldFileName.lastIndexOf(".");
        if (dotIndex > 0) {
            extension = oldFileName.substring(dotIndex); // Lưu lại cái đuôi (vd: .docx)
            baseName = oldFileName.substring(0, dotIndex); // Lưu phần tên thôi
        }
        // -------------------------------------

        // Hiển thị hộp thoại chỉ gợi ý phần tên (baseName) cho người dùng dễ gõ
        String newBaseName = javax.swing.JOptionPane.showInputDialog(
                this, 
                "Nhập tên mới :", 
                baseName);

        if (newBaseName != null && !newBaseName.trim().isEmpty()) {
            
            // TỰ ĐỘNG GHÉP LẠI TÊN MỚI + ĐUÔI CŨ
            String newFileName = newBaseName + extension;
            
            java.net.Socket socket = new java.net.Socket(client.LoginForm.SERVER_IP, 8888);
            java.io.DataOutputStream dos = new java.io.DataOutputStream(socket.getOutputStream());
            java.io.DataInputStream dis = new java.io.DataInputStream(socket.getInputStream());

            dos.writeUTF("RENAME");
            dos.writeUTF(client.LoginForm.currentUserInfo);
            dos.writeUTF(oldFileName); 
            dos.writeUTF(newFileName); 

            String response = dis.readUTF();
            textAreaFile.append("<<< " + response + "\n\n");

            socket.close();
        }
    }
} catch (Exception ex) {
    textAreaFile.append("Lỗi kết nối tới Server: " + ex.getMessage() + "\n\n");
}
    }//GEN-LAST:event_btndoiten1ActionPerformed

