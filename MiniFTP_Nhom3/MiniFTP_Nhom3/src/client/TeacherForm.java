    private void upfileActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_upfileActionPerformed
    try {
    // 1. Mở hộp thoại chọn file
    javax.swing.JFileChooser fileChooser = new javax.swing.JFileChooser();
    int returnValue = fileChooser.showOpenDialog(this);
    
    if (returnValue == javax.swing.JFileChooser.APPROVE_OPTION) {
        java.io.File fileToUpload = fileChooser.getSelectedFile();
        long fileSize = fileToUpload.length();
        String fileName = fileToUpload.getName();
        
        textAreaFile.append("Đang chuẩn bị tải lên: " + fileName + " (" + fileSize + " bytes)\n");
        
        // Reset thanh tiến trình về 0
        progressBar.setValue(0);
        progressBar.setStringPainted(true);
        
        // =========================================================
        // 2. KHỞI TẠO MỘT LUỒNG CHẠY NGẦM (BACKGROUND THREAD)
        // Giúp giao diện không bị đơ khi truyền file nặng
        // =========================================================
        Thread uploadThread = new Thread(() -> {
            try {
                java.net.Socket socket = new java.net.Socket(client.LoginForm.SERVER_IP, 8888);
                java.io.DataOutputStream dos = new java.io.DataOutputStream(socket.getOutputStream());
                java.io.DataInputStream dis = new java.io.DataInputStream(socket.getInputStream());
                
                // Gửi thông tin định tuyến
                dos.writeUTF("UPLOAD");
                dos.writeUTF(client.LoginForm.currentUserInfo);
                dos.writeUTF(fileName);
                dos.writeLong(fileSize); // Gửi tổng dung lượng để Server biết đường nhận
                
                // 3. TIẾN HÀNH ĐỌC FILE VÀ CẬP NHẬT PROGRESS BAR
                java.io.FileInputStream fis = new java.io.FileInputStream(fileToUpload);
                byte[] buffer = new byte[4096]; // Cắt nhỏ file thành các gói 4KB
                int bytesRead;
                long totalRead = 0;
                
                while ((bytesRead = fis.read(buffer)) != -1) {
                    dos.write(buffer, 0, bytesRead); // Gửi gói tin qua mạng
                    totalRead += bytesRead; // Cộng dồn số byte đã gửi
                    
                    // Tính toán phần trăm (0 - 100)
                    int percent = (int) ((totalRead * 100) / fileSize);
                    
                    // Yêu cầu cập nhật Giao diện một cách an toàn
                    javax.swing.SwingUtilities.invokeLater(() -> {
                        progressBar.setValue(percent);
                    });
                }
                
                fis.close();
                
                // Nhận thông báo thành công từ Server
                String response = dis.readUTF();
                
                // Cập nhật text area an toàn từ luồng ngầm
                javax.swing.SwingUtilities.invokeLater(() -> {
                    textAreaFile.append("<<< " + response + "\n\n");
                    javax.swing.JOptionPane.showMessageDialog(null, "Tải file hoàn tất!");
                });
                
                socket.close();
                
            } catch (Exception ex) {
                javax.swing.SwingUtilities.invokeLater(() -> {
                    textAreaFile.append("Lỗi kết nối tải lên: " + ex.getMessage() + "\n\n");
                });
            }
        });
        
        // Kích hoạt luồng chạy ngầm
        uploadThread.start();
    }
} catch (Exception ex) {
    textAreaFile.append("Lỗi mở file: " + ex.getMessage() + "\n");
}
    }//GEN-LAST:event_upfileActionPerformed

