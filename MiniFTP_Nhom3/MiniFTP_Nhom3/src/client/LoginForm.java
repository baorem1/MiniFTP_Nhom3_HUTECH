    private void btnDangNhapActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDangNhapActionPerformed
try {
    String username = txtUsername.getText();
    String password = txtPassword.getText(); 

    if(username.isEmpty() || password.isEmpty()){
        javax.swing.JOptionPane.showMessageDialog(this, "Vui lòng nhập tài khoản và mật khẩu!");
        return;
    }

    // Kết nối MySQL qua IP mạng LAN
    String dbURL = "jdbc:mysql://10.15.49.151:3306/MiniFTP_DB";
    java.sql.Connection conn = java.sql.DriverManager.getConnection(dbURL, "root", "");

    // CẬP NHẬT: Truy vấn lấy thêm Role, HoTen và MaSo từ CSDL
    String sql = "SELECT Role, HoTen, MaSo FROM Users WHERE Username=? AND Password=?";
    java.sql.PreparedStatement pstmt = conn.prepareStatement(sql);
    pstmt.setString(1, username);
    pstmt.setString(2, password);

    java.sql.ResultSet rs = pstmt.executeQuery();

    if (rs.next()) {
        String role = rs.getString("Role");
        String hoTen = rs.getString("HoTen");
        String maSo = rs.getString("MaSo");
        
        // Gộp tên và mã số lại thành một chuỗi danh tính thông minh
        client.LoginForm.currentUserInfo = hoTen + " - " + maSo; 

        javax.swing.JOptionPane.showMessageDialog(this, "Đăng nhập thành công! Xin chào: " + hoTen);
        
        this.dispose(); // Tắt form Login

        // Phân luồng mở Form tương ứng dựa vào Database
        if (role.equals("GiaoVien")) {
            new TeacherForm().setVisible(true);
        } else {
            new StudentForm().setVisible(true);
        }
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Sai tài khoản hoặc mật khẩu!", "Lỗi truy cập", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    conn.close();
} catch (Exception ex) {
    javax.swing.JOptionPane.showMessageDialog(this, "Lỗi kết nối CSDL: " + ex.getMessage());
}
    }//GEN-LAST:event_btnDangNhapActionPerformed

