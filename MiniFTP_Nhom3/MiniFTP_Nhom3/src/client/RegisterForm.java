    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
try {
        String username = txtUsername.getText();
        String password = new String(txtPassword.getPassword());
        String role = cbxRole.getSelectedItem().toString();
        
        // Lấy thêm dữ liệu từ 2 ô mới tạo trên giao diện
        String hoTen = txtHoTen1.getText();
        String maSo = txtMaSo.getText();

        // Kiểm tra điều kiện nhập liệu (bổ sung kiểm tra rỗng cho Họ tên và Mã số)
        if (username.isEmpty() || password.isEmpty() || hoTen.isEmpty() || maSo.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Vui lòng nhập đủ thông tin!");
            return;
        }

        // ==========================================
        // THÊM LỚP BẢO MẬT CHO TÀI KHOẢN GIÁO VIÊN
        // ==========================================
        if (role.equals("GiaoVien")) {
            String secretCode = javax.swing.JOptionPane.showInputDialog(
                this, 
                "Vui lòng nhập Mã Bí Mật để tạo tài khoản Giáo viên:", 
                "Xác thực cấp quyền", 
                javax.swing.JOptionPane.WARNING_MESSAGE
            );
            
            // Quy định mã bí mật ở đây
            if (secretCode == null || !secretCode.equals("123")) {
                javax.swing.JOptionPane.showMessageDialog(this, "Mã bí mật không chính xác! Đăng ký thất bại.", "Cảnh báo", javax.swing.JOptionPane.ERROR_MESSAGE);
                return; // Cắt ngang, không chạy xuống đoạn lưu Database bên dưới
            }
        }
        // ==========================================

        // Đã đổi sang đường dẫn kết nối chuẩn của MySQL
        String dbURL = "jdbc:mysql://10.15.49.151:3306/MiniFTP_DB";
        java.sql.Connection conn = java.sql.DriverManager.getConnection(dbURL, "root", "");

        // Cập nhật câu lệnh SQL để Insert đủ 5 cột
        String sql = "INSERT INTO Users (Username, Password, Role, HoTen, MaSo) VALUES (?, ?, ?, ?, ?)";
        java.sql.PreparedStatement pstmt = conn.prepareStatement(sql);
        pstmt.setString(1, username);
        pstmt.setString(2, password);
        pstmt.setString(3, role);
        pstmt.setString(4, hoTen); // Ghi thông tin Họ tên
        pstmt.setString(5, maSo);  // Ghi thông tin Mã số

        int rows = pstmt.executeUpdate();
        if (rows > 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Đăng ký thành công!");
            this.dispose(); // Đóng form đăng ký
            new LoginForm().setVisible(true); // Quay lại trang đăng nhập
        }
        conn.close();
    } catch (Exception ex) {
        javax.swing.JOptionPane.showMessageDialog(this, "Lỗi đăng ký (Có thể do trùng tài khoản): " + ex.getMessage());
    }
    }//GEN-LAST:event_jButton1ActionPerformed

